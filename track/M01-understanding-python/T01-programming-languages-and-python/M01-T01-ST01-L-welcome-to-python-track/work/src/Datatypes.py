#int 
a =10
print(type(a),a)
    # <class 'int'> 10

#float
b = 10.5
print(type(b),b)
    # <class 'float'> 10.5

#bool
c = True        #true or False
print(type(c),c)
    # <class 'bool'> True
    
#string
d = "Nandhini"       #' ' or """ """ 
print(type(d),d)
    # <class 'str'> Nandhini

#list
e = [1,2,3,4,5]
print(type(e),e)
    # <class 'list'> [1, 2, 3, 4, 5]

#tuple
f = (1,2,3,4,5)
print(type(f),f)
    # <class 'tuple'> (1, 2, 3, 4, 5)

#set
g = {1,2,3,4,5}
print(type(g),g)
    # <class 'set'> {1, 2, 3, 4, 5}

#dictionary
h = {"name":"Nandhini", "age":22}
print(type(h),h)
    # <class 'dict'> {'name': 'Nandhini', 'age': 22}

#complex
i = 10+20j
print(type(i),i)
    # <class 'complex'> (10+20j)

#None
is_valid = None
print(type(is_valid),is_valid)
    # <class 'NoneType'>